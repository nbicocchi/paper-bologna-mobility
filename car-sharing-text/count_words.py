"""Report manuscript words, including tables/captions, using TeXcount.

Includes title, abstract, keywords, headings, body, acknowledgments and
declarations. Excludes author details, references, equations and the count
statement itself. Numerical result macros are expanded before counting.
"""
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent


def expand_inputs(text):
    def include(match):
        name = match.group(1)
        if name == 'wordcount':
            return ''
        path = ROOT / name
        if not path.suffix:
            path = path.with_suffix('.tex')
        return expand_inputs(path.read_text())

    return re.sub(r'\\input\{([^}]+)\}', include, text)


def main():
    text = expand_inputs((ROOT / 'main.tex').read_text())
    numbers = dict(re.findall(
        r'\\newcommand\{\\(\w+)\}\{([^{}]+)\}', text))
    text = re.sub(r'\\newcommand\{\\\w+\}\{[^{}]+\}', '', text)
    for name, value in numbers.items():
        text = re.sub(r'\\' + re.escape(name) + r'(?![A-Za-z])(?:\{\})?',
                      lambda match: value, text)
    # Count table cells as text, retaining normal heading/caption handling.
    rules = ('%TC:envir table 0 1\n'
             '%TC:envir figure 0 1\n'
             '%TC:envir tabular 1 1\n')
    result = subprocess.run(
        ['texcount', '-sum=1,1,1', '-1', '-'], input=rules + text,
        text=True, capture_output=True, check=True, cwd=ROOT)
    count = int(result.stdout.strip())
    statement = (
        '% Generated by count_words.py; do not edit.\n'
        '\\noindent\\textbf{Word count:} ' + f'{count:,}' +
        ' (including tables and figure/table captions; excluding references, '
        'author details and equations).\\par\n')
    path = ROOT / 'wordcount.tex'
    if not path.exists() or path.read_text() != statement:
        path.write_text(statement)
    print(f'Manuscript word count: {count:,} (including tables and captions).')


if __name__ == '__main__':
    main()
