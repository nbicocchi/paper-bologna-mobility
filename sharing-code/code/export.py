"""Generate all paper tables and experiment figures from the new standalone outputs."""
import json
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from common import OUT, TEXT, FEATURES
from describe import save

LABEL = {'bike': 'Bicycle', 'car': 'Motor vehicle'}
TESTS = [('new', 2023, 'New 2023'), ('new', 2024, 'New 2024'), ('known', 2024, 'Known 2024')]


def table(name, columns, header, rows):
    lines = ['% Generated by sharing-code/code/export.py; do not edit.',
             r'\begin{tabular}{' + columns + '}', r'\toprule', ' & '.join(header) + r' \\', r'\midrule']
    lines += [' & '.join(map(str, row)) + r' \\' for row in rows]
    lines += [r'\bottomrule', r'\end{tabular}']
    (TEXT / 'tables' / f'{name}.tex').write_text('\n'.join(lines) + '\n')


def export_tables(summary, contrasts, persistence):
    rows = []
    for family in ['Boosting', 'Poisson', 'Scaling']:
        for feature in (FEATURES if family != 'Scaling' else ['Geometry']):
            cells = [family, feature if family != 'Scaling' else 'Uniform chord']
            for mode in ['bike', 'car']:
                for scenario, year, _ in TESTS:
                    r = summary.loc[(summary['mode'] == mode) & (summary.scenario == scenario) & (summary.year == year)
                                    & (summary.family == family) & (summary.feature == feature)].iloc[0]
                    cells.append(f'{100 * r.pooled_wape:.2f}')
            rows.append(cells)
    table('pooled', 'llrrrrrr', ['Learner', 'Inputs', 'Bike new 23', 'Bike new 24', 'Bike known 24',
                                'Vehicle new 23', 'Vehicle new 24', 'Vehicle known 24'], rows)
    rows = []
    c = contrasts.loc[contrasts.kind.eq('vs_context')]
    for mode in ['bike', 'car']:
        for scenario, year, label in TESTS:
            for family in ['Boosting', 'Poisson']:
                for feature in FEATURES[1:]:
                    r = c.loc[(c['mode'] == mode) & (c.scenario == scenario) & (c.year == year)
                              & (c.family == family) & (c.feature == feature)].iloc[0]
                    rows.append([LABEL[mode], label, family, feature, f'{r.delta_pp:+.2f}',
                                 f'[{r.lo_pp:+.2f}, {r.hi_pp:+.2f}]', f'{r.improved_sites}/{r.positive_sites}'])
    table('contrasts', 'llllrrr', ['Target', 'Test', 'Learner', 'Inputs', r'$\Delta$ pp', 'Spatial interval', 'Sites improved'], rows)
    rows = [[r.mode, r.family, r.feature, r.common_positive_sites, r.improve_both, r.improve_2023_only,
             r.improve_2024_only, r.improve_neither] for r in persistence.itertuples()]
    table('persistence', 'lllrrrrr', ['Target', 'Learner', 'Inputs', r'$S_+$', 'Both', '2023 only', '2024 only', 'Neither'], rows)
    rows = []
    for year in [2023, 2024]:
        cells = [year]
        for mode in ['bike', 'car']:
            r = pd.read_csv(OUT / f'{mode}-rental-audit.csv').set_index('year').loc[year]
            cells += [f'{int(r.raw):,}', f'{int(r.retained):,}']
        rows.append(cells)
    table('audit', 'lrrrr', ['Year', 'Bike raw', 'Bike retained', 'Car raw', 'Car retained'], rows)
    regions = pd.read_csv(OUT / 'rhythm-regions.csv')
    rows = []
    for mode in ['bike', 'car']:
        for region in ['Centre', 'Northern band', 'Remaining area']:
            r = regions.loc[(regions['mode'] == mode) & (regions.region == region)].set_index('window')
            rows.append([mode.capitalize(), region, f'{100*r.loc[0, "normalised_balance"]:+.1f}',
                         f'{100*r.loc[2, "normalised_balance"]:+.1f}'])
    table('urban-rhythms', 'llrr', ['Source', 'Area', '06--10', '15--20'], rows)
    rows = [[r.mode, r.scenario, r.year, r.family, r.feature, r.sites, r.positive_sites,
             f'{100*r.pooled_wape:.2f}', f'{100*r.median_wape:.2f}', f'{100*r.macro_wape:.2f}', f'{100*r.pooled_bias:+.2f}']
            for r in summary.itertuples()]
    table('all-metrics', 'llrllrrrrrr', ['Target', 'Scenario', 'Year', 'Learner', 'Inputs', r'$S$', r'$S_+$', 'Pooled', 'Median', 'Macro', 'Bias'], rows)


def figures(summary, contrasts, persistence):
    colors = ['#0072b2', '#d55e00', '#009e73']
    fig, axes = plt.subplots(2, 2, figsize=(10, 6.5), sharex=True, layout='constrained')
    for row, mode in enumerate(['bike', 'car']):
        for column, family in enumerate(['Boosting', 'Poisson']):
            ax = axes[row, column]
            for (scenario, year, label), color, style in zip(TESTS, colors, ['-o', '--s', '-.^']):
                r = summary.loc[(summary['mode'] == mode) & (summary.family == family)
                                & (summary.scenario == scenario) & (summary.year == year)].set_index('feature')
                ax.plot(FEATURES, r.loc[FEATURES].pooled_wape * 100, style, color=color, label=label)
            ax.set(title=f'{LABEL[mode]} / {family}', ylabel='Pooled WAPE (%)')
            ax.grid(axis='y', alpha=.2)
    axes[0, 0].legend(fontsize=8)
    save(fig, 'feature-ladder')
    fig, axes = plt.subplots(2, 2, figsize=(10, 6), layout='constrained')
    for row, mode in enumerate(['bike', 'car']):
        for column, family in enumerate(['Boosting', 'Poisson']):
            ax = axes[row, column]
            for scenario, color, offset in [('new', colors[1], -.1), ('known', colors[2], .1)]:
                r = contrasts.loc[(contrasts['mode'] == mode) & (contrasts.scenario == scenario) & (contrasts.year == 2024)
                                  & (contrasts.family == family) & contrasts.kind.eq('vs_context')].set_index('feature').loc[FEATURES[1:]]
                y = np.arange(3) + offset
                ax.hlines(y, r.lo_pp, r.hi_pp, color=color, lw=2)
                ax.scatter(r.delta_pp, y, color=color, label=f'{scenario.capitalize()} location')
            ax.axvline(0, color='grey', lw=1)
            ax.set_yticks(np.arange(3), FEATURES[1:])
            ax.invert_yaxis()
            ax.set(title=f'{LABEL[mode]} / {family} / 2024', xlabel='Sharing minus Context (percentage points)')
    axes[0, 0].legend(fontsize=8)
    save(fig, 'paired-contrasts')
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.7), sharey=True, layout='constrained')
    states = [('improve_both', 'Both years', '#009e73'), ('improve_2023_only', '2023 only', '#0072b2'),
              ('improve_2024_only', '2024 only', '#e69f00'), ('improve_neither', 'Neither', '#bdbdbd')]
    order = [(family, feature) for family in ['Boosting', 'Poisson'] for feature in FEATURES[1:]]
    for mode, ax in zip(['bike', 'car'], axes):
        p = persistence.loc[persistence['mode'] == mode].set_index(['family', 'feature']).loc[order]
        bottom = np.zeros(6)
        for key, label, color in states:
            values = p[key].to_numpy() / p.common_positive_sites.to_numpy() * 100
            ax.bar(np.arange(6), values, bottom=bottom, color=color, label=label)
            bottom += values
        ax.set_xticks(np.arange(6), [f'{feature}\n{family}' for family, feature in order], rotation=35, ha='right', fontsize=8)
        ax.set(title=f'{LABEL[mode]} / new location', ylim=(0, 100), ylabel='Sites (%)')
    axes[1].legend(fontsize=7)
    save(fig, 'persistence')
    # Every site's 2024 gains are retained, rather than cherry-picked example sensors.
    sites = pd.read_csv(OUT / 'sites.csv')
    rows = []
    for (mode, scenario, family), g in sites.loc[sites.year.eq(2024) & sites.family.ne('Scaling')].groupby(['mode', 'scenario', 'family']):
        wide = g.pivot(index='site', columns='feature', values='wape')
        for feature in FEATURES[1:]:
            for site, delta in (100 * (wide[feature] - wide.Context)).items():
                rows.append(dict(mode=mode, scenario=scenario, family=family, feature=feature, site=site, delta_pp=delta))
    pd.DataFrame(rows).to_csv(OUT / 'local-gains-2024.csv', index=False)


def narrative(summary, contrasts, persistence):
    """Keep paper numbers tied to the rebuilt outputs, never to legacy snapshots."""
    car = json.loads((OUT / 'car-counter-design.json').read_text())
    reversals = pd.read_csv(OUT / 'rhythm-reversals.csv').set_index('mode')
    values = {'VehicleDevices': str(car['sites']), 'VehicleGroups': str(car['clusters']),
              'VehicleBlocks': str(car['blocks']),
              'BikeReversal': f'{100 * reversals.loc["bike", "reversal_fraction"]:.1f}',
              'CarReversal': f'{100 * reversals.loc["car", "reversal_fraction"]:.1f}'}
    (TEXT / 'tables' / 'result-values.tex').write_text('% Generated from the standalone run.\n' +
        ''.join('\\newcommand{\\' + name + '}{' + value + '}\n' for name, value in values.items()))
    new_paragraphs, known_paragraphs, local_paragraphs = [], [], []
    for mode in ['bike', 'car']:
        label = 'bicycle' if mode == 'bike' else 'motor-vehicle'
        s = summary.loc[summary['mode'].eq(mode)]
        sentences = []
        for year in [2023, 2024]:
            z = s.loc[s.scenario.eq('new') & s.year.eq(year) & s.family.ne('Scaling')]
            best = z.loc[z.pooled_wape.idxmin()]
            sentences.append(f'In {year}, the lowest observed {label} WAPE among the fixed new-location configurations is '
                f'{100*best.pooled_wape:.2f}\\% ({best.family}, {best.feature}).')
        for family in ['Poisson', 'Boosting']:
            c = contrasts.loc[contrasts['mode'].eq(mode) & contrasts.scenario.eq('new')
                              & contrasts.family.eq(family) & contrasts.kind.eq('vs_context') & contrasts.feature.eq('Citywide')].set_index('year')
            sentences.append(f'For {family}, the Citywide minus Context difference is '
                             f'{c.loc[2023, "delta_pp"]:+.2f} percentage points in 2023 and '
                             f'{c.loc[2024, "delta_pp"]:+.2f} in 2024.')
        new_paragraphs.append(' '.join(sentences))
        sentences = []
        k = s.loc[s.scenario.eq('known') & s.family.ne('Scaling')]
        best = k.loc[k.pooled_wape.idxmin()]
        sentences.append(f'For known {label} positions in 2024, the lowest observed WAPE among the fixed configurations is '
                         f'{100*best.pooled_wape:.2f}\\% ({best.family}, {best.feature}).')
        for family in ['Poisson', 'Boosting']:
            z = k.loc[k.family.eq(family)].set_index('feature')
            c = contrasts.loc[contrasts['mode'].eq(mode) & contrasts.scenario.eq('known')
                              & contrasts.family.eq(family) & contrasts.kind.eq('vs_context')].set_index('feature')
            deltas = ', '.join(f'{feature} {c.loc[feature, "delta_pp"]:+.2f}' for feature in FEATURES[1:])
            sentences.append(f'The history-aware {family} Context baseline has WAPE {100*z.loc["Context", "pooled_wape"]:.2f}\\%; '
                             f'sharing-minus-Context differences are {deltas} percentage points.')
        known_paragraphs.append(' '.join(sentences))
        for scenario in ['new', 'known']:
            z = s.loc[s.scenario.eq(scenario) & s.year.eq(2024) & s.family.ne('Scaling') & s.feature.ne('Context')]
            best = z.loc[z.pooled_wape.idxmin()]
            c = contrasts.loc[contrasts['mode'].eq(mode) & contrasts.scenario.eq(scenario) & contrasts.year.eq(2024)
                & contrasts.family.eq(best.family) & contrasts.feature.eq(best.feature) & contrasts.kind.eq('vs_context')].iloc[0]
            sentence = (f'For {label} {"new" if scenario == "new" else "known"} positions, '
                f'{best.family} with {best.feature} has the lowest 2024 WAPE among sharing-enhanced configurations; '
                f'{int(c.improved_sites)} of {int(c.positive_sites)} positive-total sites improve over its own Context baseline.')
            if scenario == 'new':
                p = persistence.loc[persistence['mode'].eq(mode) & persistence.family.eq(best.family)
                                    & persistence.feature.eq(best.feature)].iloc[0]
                sentence += f' Of {int(p.common_positive_sites)} common positive-total sites, {int(p.improve_both)} improve in both years.'
            local_paragraphs.append(sentence)
    new_paragraphs.append('These minima are descriptive comparisons of the prespecified configurations, not a model-selection rule using held-out data. '
                          'A gain within a learner must not be confused with the best overall estimator; the feature ladder must be read separately in each test year.')
    known_paragraphs.append('Negative differences indicate improvement. Figure~\\ref{fig:contrasts} reports the paired sensitivity intervals; '
                            'the point estimates alone do not establish robust benefit across spatial units.')
    for name, paragraphs in [('new-location-results', new_paragraphs), ('known-location-results', known_paragraphs), ('local-results', local_paragraphs)]:
        (TEXT / 'tables' / f'{name}.tex').write_text('% Generated from freshly fitted predictions.\n' + '\n\n'.join(paragraphs) + '\n')


def main():
    summary = pd.read_csv(OUT / 'summary.csv')
    contrasts = pd.read_csv(OUT / 'contrasts.csv')
    persistence = pd.read_csv(OUT / 'persistence.csv')
    export_tables(summary, contrasts, persistence)
    figures(summary, contrasts, persistence)
    narrative(summary, contrasts, persistence)


if __name__ == '__main__':
    main()
