"""Generate integrated figures and tables from the reconciled comparison."""
import json
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from common import OUT, INPUT, TEXT, FEATURES
from maps import draw_maps
from distributions import draw_distributions

LABEL = {'bike': 'Bicycle counts', 'car': 'Motor-vehicle counts'}
COLORS = ['#495057', '#0072b2', '#e69f00', '#009e73']


def table(name, columns, header, rows):
    content = ['% Generated by sharing-code/code/export.py; do not edit.',
               r'\begin{tabular}{' + columns + '}', r'\toprule',
               ' & '.join(header) + r' \\', r'\midrule']
    content += [' & '.join(map(str, row)) + r' \\' for row in rows]
    content += [r'\bottomrule', r'\end{tabular}']
    (TEXT / 'tables' / f'{name}.tex').write_text('\n'.join(content) + '\n')


def export_tables(summary, contrasts, persistence):
    rows = []
    for family in ['Boosting', 'Poisson', 'Scaling']:
        for feature in (FEATURES if family != 'Scaling' else ['Geometry']):
            cells = [family, feature if family != 'Scaling' else 'Uniform chord']
            for mode in ['bike', 'car']:
                for year in [2023, 2024]:
                    r = summary[(summary['mode'] == mode) & (summary.year == year)
                                & (summary.family == family) & (summary.feature == feature)].iloc[0]
                    cells.append(f'{100 * r.pooled_wape:.2f}')
            rows.append(cells)
    table('pooled', 'llrrrr', ['Learner', 'Inputs', 'Bike 2023', 'Bike 2024', 'Vehicle 2023', 'Vehicle 2024'], rows)
    rows = []
    for (mode, family, feature), frame in contrasts[contrasts.kind == 'vs_context'].groupby(['mode', 'family', 'feature'], sort=False):
        cells = [LABEL[mode], family, feature]
        for year in [2023, 2024]:
            r = frame[frame.year == year].iloc[0]
            cells += [f'{r.delta_pp:+.2f}', f'[{r.lo_pp:+.2f}, {r.hi_pp:+.2f}]']
        rows.append(cells)
    table('contrasts', 'lllrrrr', ['Target', 'Learner', 'Added inputs', r'$\Delta_{23}$', 'Spatial interval', r'$\Delta_{24}$', 'Spatial interval'], rows)
    rows = []
    for r in persistence.itertuples():
        rows.append([LABEL[r.mode], r.family, r.feature, r.common_positive_sites,
                     r.improve_both, r.improve_2023_only, r.improve_2024_only,
                     r.improve_neither, f'{r.advantage_change_pp:+.2f}'])
    table('persistence', 'lllrrrrrr', ['Target', 'Learner', 'Inputs', r'$S_+$', 'Both', '2023 only', '2024 only', 'Neither', r'$\Delta_{24}-\Delta_{23}$'], rows)
    rows = []
    for r in summary.itertuples():
        rows.append([r.mode.capitalize(), r.year, r.family, r.feature, r.sites, r.positive_sites,
                     f'{100*r.pooled_wape:.1f}', f'{100*r.median_wape:.1f}', f'{100*r.macro_wape:.1f}',
                     f'{100*r.pooled_bias:+.1f}'])
    table('all-metrics', 'lrllrrrrrr', ['Source', 'Year', 'Learner', 'Inputs', r'$S$', r'$S_+$', 'Pooled', 'Median', 'Macro', 'Bias'], rows)
    audits = []
    for year in [2023, 2024]:
        bike = json.loads((INPUT / f'bike-audit-{year}.json').read_text())
        car = pd.read_csv(INPUT / 'car-audit.csv').set_index('year').loc[year]
        audits.append([year, f'{bike["raw"]:,}', f'{bike["retained"]:,}',
                       f'{int(car.initial):,}', f'{int(car.retained):,}'])
    table('audit', 'lrrrr', ['Year', 'Bike raw', 'Bike retained', 'Car raw', 'Car retained'], audits)
    d = pd.read_csv(OUT / 'denominators.csv')
    table('denominators', 'llrrrr', ['Source', 'Year', r'$S$', 'Zero total', 'Min. positive total', 'Largest share'],
          [[r.mode.capitalize(), r.year, r.sites, r.zero_sites,
            f'{r.minimum_positive_total:,.0f}', f'{100*r.largest_share_of_wape_sum:.1f}\\%'] for r in d.itertuples()])


def save(fig, name):
    fig.savefig(TEXT / 'figures' / f'{name}.pdf', bbox_inches='tight',
                metadata={'CreationDate': None, 'ModDate': None})
    plt.close(fig)


def figures(summary, contrasts, persistence):
    plt.rcParams.update({'font.size': 9, 'axes.spines.top': False, 'axes.spines.right': False,
                         'pdf.fonttype': 42})
    fig, axes = plt.subplots(2, 2, figsize=(10, 6), sharex=True)
    for i, mode in enumerate(['bike', 'car']):
        for j, family in enumerate(['Boosting', 'Poisson']):
            ax = axes[i, j]
            for year, style, color in [(2023, '-o', COLORS[1]), (2024, '--s', COLORS[2])]:
                f = summary[(summary['mode'] == mode) & (summary.family == family) & (summary.year == year)].set_index('feature')
                ax.plot(FEATURES, 100*f.loc[FEATURES].pooled_wape, style, color=color, label=str(year))
            scaling = summary[(summary['mode'] == mode) & (summary.family == 'Scaling')]
            for r in scaling.itertuples():
                ax.axhline(100*r.pooled_wape, color=COLORS[0], ls=':' if r.year == 2023 else '--', alpha=.6,
                           label=f'Scaling {r.year}')
            ax.set_title(f'{LABEL[mode]} / {family}')
            ax.set_ylabel('Pooled WAPE (%)')
            ax.grid(axis='y', alpha=.2)
    axes[0, 0].legend(ncol=2, fontsize=8)
    fig.tight_layout()
    save(fig, 'feature-ladder')

    fig, axes = plt.subplots(2, 2, figsize=(10, 6), sharex=True)
    for i, mode in enumerate(['bike', 'car']):
        for j, family in enumerate(['Boosting', 'Poisson']):
            ax = axes[i, j]
            for year, offset, color in [(2023, -.12, COLORS[1]), (2024, .12, COLORS[2])]:
                f = contrasts[(contrasts['mode'] == mode) & (contrasts.family == family)
                              & (contrasts.year == year) & (contrasts.kind == 'vs_context')].set_index('feature').loc[FEATURES[1:]]
                y = np.arange(3) + offset
                # Draw percentile limits directly: the estimate need not lie inside them.
                ax.hlines(y, f.lo_pp, f.hi_pp, color=color, lw=2)
                ax.scatter(f.delta_pp, y, color=color, s=24, label=str(year))
            ax.axvline(0, color='grey', lw=1)
            ax.set_yticks(np.arange(3), FEATURES[1:])
            ax.set_title(f'{LABEL[mode]} / {family}')
            ax.set_xlabel('Sharing minus context (percentage points)')
            ax.invert_yaxis()
            ax.grid(axis='x', alpha=.2)
    axes[0, 0].legend()
    fig.tight_layout()
    save(fig, 'paired-contrasts')

    fig, axes = plt.subplots(1, 2, figsize=(10, 3.5), sharey=True)
    states = [('improve_both', 'Both years', '#009e73'),
              ('improve_2023_only', '2023 only', '#0072b2'),
              ('improve_2024_only', '2024 only', '#e69f00'),
              ('improve_neither', 'Neither year', '#bdbdbd')]
    for ax, mode in zip(axes, ['bike', 'car']):
        frame = persistence[persistence['mode'] == mode].set_index(['family', 'feature'])
        order = [(family, feature) for family in ['Boosting', 'Poisson'] for feature in FEATURES[1:]]
        frame = frame.loc[order]
        bottom = np.zeros(len(frame))
        for column, label, color in states:
            values = frame[column].to_numpy() / frame.common_positive_sites.to_numpy() * 100
            ax.bar(np.arange(6), values, bottom=bottom, color=color, label=label)
            bottom += values
        ax.set_title(f'{LABEL[mode]} (common positive-total sites)')
        ax.set_xticks(np.arange(6), [f'{f}\n{l}' for l, f in order], rotation=35, ha='right')
        ax.set_ylim(0, 100)
    axes[0].set_ylabel('Sites (%)')
    axes[1].legend(fontsize=8, loc='upper left', bbox_to_anchor=(1, 1))
    fig.tight_layout()
    save(fig, 'persistence')


def main():
    for directory in [TEXT / 'tables', TEXT / 'figures']:
        directory.mkdir(parents=True, exist_ok=True)
    summary = pd.read_csv(OUT / 'summary.csv')
    contrasts = pd.read_csv(OUT / 'contrasts.csv')
    persistence = pd.read_csv(OUT / 'persistence.csv')
    export_tables(summary, contrasts, persistence)
    figures(summary, contrasts, persistence)
    draw_maps()
    draw_distributions()
    regions = pd.read_csv(OUT / 'rhythm-regions.csv')
    rows = []
    for mode in ['bike', 'car']:
        for region in ['Centre', 'Northern band', 'Remaining area']:
            f = regions[(regions['mode'] == mode) & (regions.region == region)].set_index('window')
            rows.append([mode.capitalize(), region,
                         f'{100*f.loc[0, "normalised_balance"]:+.1f}',
                         f'{100*f.loc[2, "normalised_balance"]:+.1f}'])
    table('urban-rhythms', 'llrr', ['Source', 'Area', '06--10', '15--20'], rows)
    print('Exported tables, three comparison figures, two sharing maps, a sensor map and an eight-panel sharing figure.')


if __name__ == '__main__':
    main()
